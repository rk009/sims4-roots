import { describe, it, expect } from 'vitest';
import characterSeed from '../../release/conf/characters.json?raw';
import familySeed from '../../release/conf/families.json?raw';
import worldSeed from '../../release/conf/worlds.json';
import { parseWorkspace, splitWorkspace, replaceCharacter, replaceFamily, familyTitle, addCharacter, deleteCharacter, upgradeDraft, type Family } from './model';
import { layoutTree } from './tree';
import { occultIcon, statusIcon } from './assets';
const characters = JSON.stringify([{characterName:'A',displayName:'Alpha',brotherNumber:2,partners:[{characterName:'B',status:'married'}]},{characterName:'B'},{characterName:'C',father:'A',mother:'B',brotherNumber:1},{characterName:'Unused'}]);
const families = JSON.stringify([{familyName:'One',members:['A','B','C'],pets:['Dog']},{familyName:'Two',members:['A']}]);
describe('split configuration',()=>{
  it('loads the actual hand-edited release files',()=>{
    const data=parseWorkspace(characterSeed,familySeed);
    expect(worldSeed.map(entry=>entry.world)).toContain('Chestnut Ridge');
    expect(data.some(f=>f.world==='Chesnut Ridge')).toBe(false);
    expect(data.map(f=>f.familyName)).toEqual([...familySeed.matchAll(/"familyName"\s*:\s*"([^"]+)"/g)].map(match=>match[1]));
    for(const f of data)expect(layoutTree(data,f).nodes.every(n=>Number.isFinite(n.x))).toBe(true);
    const saved=splitWorkspace(data);
    expect(saved.families.flatMap(f=>f.members).every(name=>typeof name==='string')).toBe(true);
    expect(saved.characters.find(c=>c.characterName==='Jonathan Joestar')?.brotherNumber).toBe(1);
    expect(saved.characters.some(c=>c.characterName==='Shinichi Sono')).toBe(true);
    expect(saved.characters.every(c=>!Object.hasOwn(c,'brothers'))).toBe(true);
    expect(saved.characters.filter(c=>c.father?.startsWith('noparents_')).length).toBeGreaterThan(0);
    expect(saved.families.find(f=>f.members.includes('Shinichi Sono'))?.members).toContain('Misato Sono');
    expect(saved.characters.find(c=>c.characterName==='Shinichi Sono')?.partners).toContainEqual({characterName:'Misato Sono',status:'love_marriage'});
    expect(saved.characters.find(c=>c.characterName==='Rikyel Joestar')?.twins).toContain('Ungaro Joestar');
    const zeppeli=data.find(f=>f.members.some(c=>c.characterName==='Joseph Joestar') && f.members.some(c=>c.characterName==='Josuke Higashikata'))!;
    const tree=layoutTree(data,zeppeli);
    expect(tree.nodes.some(n=>n.character.characterName==='Tomoko Higashikata')).toBe(true);
    expect(tree.nodes.find(n=>n.character.characterName==='Joseph Joestar')?.partners.some(p=>p.characterName==='Tomoko Higashikata')).toBe(false);
    const joseph=tree.nodes.find(n=>n.character.characterName==='Joseph Joestar')!;
    const suzi=tree.nodes.find(n=>n.character.characterName==='Suzi Quadro')!;
    const caesar=tree.nodes.find(n=>n.character.characterName==='Caesar Zeppeli')!;
    const tomoko=tree.nodes.find(n=>n.character.characterName==='Tomoko Higashikata')!;
    const caesarBond=tree.bonds.find(b=>[b.a,b.b].some(n=>n.character.characterName==='Caesar Zeppeli'))!;
    const suziBond=tree.bonds.find(b=>[b.a,b.b].some(n=>n.character.characterName==='Suzi Quadro'))!;
    const tomokoBond=tree.bonds.find(b=>[b.a,b.b].some(n=>n.character.characterName==='Tomoko Higashikata'))!;
    expect(caesar.x).toBeLessThan(suzi.x);
    expect(suzi.x).toBeLessThan(joseph.x);
    expect(joseph.x).toBeLessThan(tomoko.x);
    expect(caesarBond.x).toBeGreaterThan(caesar.x+100);
    expect(caesarBond.x).toBeLessThan(suzi.x);
    expect(tree.lines.some(line=>line.partnerLink && line.d.startsWith(`M ${caesarBond.x} ${caesarBond.y-21} V `) && line.d.endsWith(`V ${joseph.y-3}`))).toBe(true);
    expect(suziBond.x).toBeGreaterThan(suzi.x+100);
    expect(suziBond.x).toBeLessThan(joseph.x);
    expect(tomokoBond.x).toBeGreaterThan(joseph.x+100);
    expect(tomokoBond.x).toBeLessThan(tomoko.x);
    expect(tree.lines.some(line=>line.d.startsWith(`M ${tomokoBond.x} ${tomokoBond.y+21} V `))).toBe(true);
    const joestar=data.find(f=>f.members.some(c=>c.characterName==='Jonathan Joestar'))!;
    const joestarTree=layoutTree(data,joestar);
    const jonathan=joestarTree.nodes.find(n=>n.character.characterName==='Jonathan Joestar')!;
    const dioBond=joestarTree.bonds.find(b=>b.a.character.characterName==='Jonathan Joestar' && b.b.character.characterName==='Dio Joestar')!;
    expect(jonathan.partners.some(p=>p.characterName==='Erina Pendleton')).toBe(true);
    expect(dioBond.x-21).toBeGreaterThanOrEqual(jonathan.x+110+78);
    const pendleton=data.find(f=>f.members.some(c=>c.characterName==='Erina Pendleton'))!;
    const externalJonathan=layoutTree(data,pendleton).nodes.find(n=>n.character.characterName==='Jonathan Joestar')!;
    expect(externalJonathan.external).toBe(true);
    expect(externalJonathan.partners).toEqual([]);
  });
  it('keeps personal records and unused characters separate from memberships',()=>{
    const data=parseWorkspace(characters,families), saved=splitWorkspace(data);
    expect(saved.characters).toHaveLength(4);
    expect(saved.characters.every(c=>c.isDead===false)).toBe(true);
    expect(saved.characters[0].brotherNumber).toBe(2);
    expect(saved.families[0].members).toEqual(['A','B','C']);
    expect(saved.families[1].members).toEqual(['A']);
    expect(saved.characters[0].partners).toEqual([{characterName:'B',status:'married'}]);
    expect(parseWorkspace(JSON.stringify(saved.characters),JSON.stringify(saved.families))[0].pets).toEqual(['Dog']);
  });
  it('keeps a family identifier separate from its display name and updates main household links on rename',()=>{
    const data=parseWorkspace(JSON.stringify([{characterName:'A',mainFamily:'One'},{characterName:'B',mainFamily:'One'}]),JSON.stringify([{familyName:'One',displayName:'一番目の家',members:['A'],formerMembers:['B']},{familyName:'Two',members:['B']}]));
    expect(familyTitle(data[0])).toBe('一番目の家');
    expect(familyTitle(data[1])).toBe('Two');
    const renamed=replaceFamily(data,0,{...data[0],familyName:'First',displayName:'新しい表示名'});
    expect(renamed[0].members[0].mainFamily).toBe('First');
    expect(renamed[0].formerMembers?.[0].mainFamily).toBe('First');
    expect(renamed[1].members[0].mainFamily).toBe('First');
    expect(data[0].members[0].mainFamily).toBe('One');
    const saved=splitWorkspace(renamed);
    expect(saved.families[0].displayName).toBe('新しい表示名');
    expect(saved.characters.find(c=>c.characterName==='B')?.mainFamily).toBe('First');
    expect(parseWorkspace(JSON.stringify(saved.characters),JSON.stringify(saved.families))[0].formerMembers?.[0].mainFamily).toBe('First');
    expect(()=>replaceFamily(renamed,0,{...renamed[0],familyName:'Two'})).toThrow();
  });
  it('keeps former members at full size through save, reload, edits, and deletion',()=>{
    const data=parseWorkspace(characters,JSON.stringify([{familyName:'One',members:['A','C'],formerMembers:['B']}])) , tree=layoutTree(data,data[0]);
    const former=tree.nodes.find(node=>node.character.characterName==='B')!;
    expect(former.former).toBe(true);
    expect(former.external).toBe(false);
    expect(former.width).toBeGreaterThanOrEqual(116);
    expect(tree.bonds.some(bond=>[bond.a,bond.b].includes(former))).toBe(true);
    const saved=splitWorkspace(data);
    expect(saved.families[0].formerMembers).toEqual(['B']);
    expect(saved.families[0].members).toEqual(['A','C']);
    const loaded=parseWorkspace(JSON.stringify(saved.characters),JSON.stringify(saved.families));
    expect(loaded[0].formerMembers?.[0].characterName).toBe('B');
    const edited=replaceCharacter(loaded,0,-4,{...loaded[0].formerMembers![0],characterName:'Bee',displayName:'Bee'},'B');
    expect(edited[0].formerMembers?.[0].displayName).toBe('Bee');
    expect(edited[0].members.find(c=>c.characterName==='C')?.mother).toBe('Bee');
    expect(deleteCharacter(edited,'Bee')[0].formerMembers).toEqual([]);
  });
  it('resolves every configured status and occult icon',()=>{
    for(const status of ['married','love_marriage','marriage_of_convenience','engaged','dating','brokenup','divorced','widowed','bestfriend','summser_fling','friendzone_right','friendzone_left','flirting','family'])expect(statusIcon(status)).toBeTruthy();
    for(const occult of ['ghost','alien','vampire','spellcaster','werewolf','mermaid','fairy','servo','plant_sim','sulanimana'])expect(occultIcon(occult)).toBeTruthy();
  });
  it('stores the death flag with the character and validates its type',()=>{
    const deadCharacters=JSON.stringify([{characterName:'A',isDead:true},{characterName:'B',isDead:false}]);
    const deadFamilies=JSON.stringify([{familyName:'One',members:['A','B']}]);
    const saved=splitWorkspace(parseWorkspace(deadCharacters,deadFamilies));
    expect(saved.characters.map(c=>c.isDead)).toEqual([true,false]);
    expect(saved.families[0].members).toEqual(['A','B']);
    expect(()=>parseWorkspace(JSON.stringify([{characterName:'A',isDead:'true'}]),deadFamilies)).toThrow();
  });
  it('shares personal edits and sibling order across families',()=>{
    const data=parseWorkspace(characters,families);
    const edited=replaceCharacter(data,0,0,{...data[0].members[0],characterName:'Z',displayName:'Zulu',brotherNumber:4});
    expect(edited[1].members[0].displayName).toBe('Zulu');
    expect(edited[1].members[0].brotherNumber).toBe(4);
    expect(edited[0].members[2].father).toBe('Z');
    const saved=splitWorkspace(edited);
    expect(saved.characters.some(c=>c.characterName==='A')).toBe(false);
    expect(saved.characters.find(c=>c.characterName==='Z')?.brotherNumber).toBe(4);
  });
  it('migrates older family-level sibling order on load',()=>{
    const oldCharacters=JSON.stringify([{characterName:'A'},{characterName:'B'}]);
    const oldFamilies=JSON.stringify([{familyName:'Old',members:[{characterName:'A',brotherNumber:3,twins:['B'],partners:[{characterName:'B',member:true}]}]}]);
    const saved=splitWorkspace(parseWorkspace(oldCharacters,oldFamilies));
    expect(saved.characters.find(c=>c.characterName==='A')?.brotherNumber).toBe(3);
    expect(saved.characters.find(c=>c.characterName==='A')?.twins).toEqual(['B']);
    expect(saved.families[0].members).toEqual(['A','B']);
  });
  it('upgrades older drafts with full-size partners',()=>{
    const old=[{familyName:'Old',world:'',members:[{characterName:'A',partners:[{characterName:'B',status:'married',member:true}]}],catalog:[{characterName:'A'},{characterName:'B',displayName:'Bravo'}]}] as unknown as Family[];
    const upgraded=upgradeDraft(old);
    expect(upgraded[0].members.map(c=>c.characterName)).toEqual(['A','B']);
    expect(upgraded[0].members[1].displayName).toBe('Bravo');
    expect(splitWorkspace(upgraded).families[0].members).toEqual(['A','B']);
    expect(splitWorkspace(upgraded).characters.find(c=>c.characterName==='A')?.partners).toEqual([{characterName:'B',status:'married'}]);
  });
  it('places a declared partner at full size and starts the child line below the status icon',()=>{
    const data=parseWorkspace(characters,families), tree=layoutTree(data,data[0]);
    const a=tree.nodes.find(n=>n.character.characterName==='A')!, b=tree.nodes.find(n=>n.character.characterName==='B')!;
    expect(b.y).toBe(a.y);expect(b.x).toBeGreaterThan(a.x);
    const bond=tree.bonds[0];expect(tree.lines.some(l=>l.d.startsWith(`M ${bond.x} ${bond.y+21} V`))).toBe(true);
    expect(bond.x-(a.x+a.left+50)).toBe((b.x+b.left+50)-bond.x);
  });
  it('edits a catalog-only partner without adding family membership',()=>{
    const data=parseWorkspace(characters,families);
    const edited=replaceCharacter(data,1,-2,{characterName:'B',displayName:'Bravo'},'B');
    expect(edited[1].members).toHaveLength(1);
    expect(splitWorkspace(edited).characters.find(c=>c.characterName==='B')?.displayName).toBe('Bravo');
  });
  it('adds a character globally and removes its memberships and references when deleted',()=>{
    const data=parseWorkspace(characters,families);
    const added=addCharacter(data,{characterName:'D',displayName:'Delta'});
    expect(splitWorkspace(added).characters.find(c=>c.characterName==='D')?.displayName).toBe('Delta');
    expect(splitWorkspace(added).families.flatMap(f=>f.members)).not.toContain('D');
    const removed=deleteCharacter(data,'A');
    const saved=splitWorkspace(removed);
    expect(saved.characters.some(c=>c.characterName==='A')).toBe(false);
    expect(saved.families.some(f=>f.members.includes('A'))).toBe(false);
    expect(saved.characters.find(c=>c.characterName==='C')?.father).toBe('');
  });
});
